"""Slack Block Kit payload for the daily Trino query-cost report.

Separate message from Cryo's fleet-health daily report (``cryo.reporting.daily_report``) --
same reasoning as ``cryo.anomalies.slack``'s shared-S3 report: a distinct question deserves its
own message rather than another section bolted onto an already-dense digest. Sent to the same
``SlackConfig`` rows (see ``cryo.reporting.query_cost_report.notify_query_cost_report``), so it
reaches whatever channel(s) the fleet-health report already reaches with no separate webhook to
configure.
"""

from __future__ import annotations

from datetime import datetime
from typing import Any

from cryo.reporting.query_cost_signals import (
    UNKNOWN_CLIENT_FLAG_SHARE_PCT,
    ClientQueryCost,
    QueryCostSignal,
    UserQueryCost,
)
from cryo.reporting.slack import (
    SlackBlock,
    context_block,
    divider_block,
    header_block,
    section_block,
    table_block,
)

MAX_SLACK_CLIENTS = 8
MAX_SLACK_USERS = 8

_SEVERITY_EMOJI = {"high": "🔴", "medium": "🟡", "low": "🟢"}


def _fmt_usd(v: float | None) -> str:
    return f"${v:,.2f}" if v is not None else "n/a"


def _fmt_gb(bytes_: int) -> str:
    gb = bytes_ / (1024**3)
    if gb >= 1024:
        return f"{gb / 1024:.2f} TB"
    return f"{gb:.1f} GB"


def _direction_emoji(direction: str) -> str:
    return {"spike": "📈", "decline": "📉", "stable": "➖"}.get(direction, "➖")


def build_query_cost_slack_blocks(
    signal: QueryCostSignal,
    *,
    generated_at: datetime,
    bottom_line: str | None = None,
    action_items: list[dict[str, Any]] | None = None,
) -> list[SlackBlock]:
    date_str = generated_at.strftime("%B %d, %Y")
    blocks: list[SlackBlock] = [header_block(f"💰 Trino Query Cost Report — {date_str}")]

    current = signal.current
    if current is None:
        blocks.append(
            section_block(
                "No Trino query-cost data has been ingested yet for yesterday "
                "(`QueryCostAttributionDaily` has no row for that day)."
            )
        )
        blocks.append(divider_block())
        blocks.append(context_block([f"Generated by Cryo at {generated_at.strftime('%H:%M UTC')}"]))
        return blocks

    emoji = _direction_emoji(signal.direction)
    if signal.direction == "stable":
        headline = f"{emoji} *Stable* — no significant DoD or WoW move"
    else:
        pct = signal.dod_pct if signal.primary_signal == "dod" else signal.wow_pct
        window = "day-over-day" if signal.primary_signal == "dod" else "week-over-week"
        pct_str = f" ({pct:+.1f}% {window})" if pct is not None else ""
        headline = f"{emoji} *{signal.direction.title()}*{pct_str}"
    blocks.append(section_block(headline))

    if bottom_line:
        blocks.append(section_block(bottom_line))

    dod_str = f"{signal.dod_pct:+.1f}%" if signal.dod_pct is not None else "n/a"
    wow_str = f"{signal.wow_pct:+.1f}%" if signal.wow_pct is not None else "n/a"
    blocks.append(
        table_block(
            ["Metric", "Yesterday"],
            [
                ["💵 Estimated Scan Cost", _fmt_usd(current.estimated_scan_cost_usd)],
                ["📊 Queries", f"{current.query_count:,} ({current.failed_query_count:,} failed)"],
                ["💾 Data Scanned", _fmt_gb(current.physical_bytes_scanned)],
                ["📅 DoD Change", dod_str],
                ["📅 WoW Change", wow_str],
            ],
        )
    )

    fsig = signal.failure_signal
    if fsig is not None and fsig.current_rate_pct is not None:
        blocks.append(divider_block())
        f_emoji = {"spike": "🔴", "decline": "🟢", "stable": "➖"}.get(fsig.direction, "➖")
        rate_str = f"{fsig.current_rate_pct:.1f}%"
        if fsig.direction == "stable":
            f_headline = f"{f_emoji} *Failure rate*: {rate_str} — no significant DoD or WoW move"
        else:
            points = fsig.dod_pct_points if fsig.primary_signal == "dod" else fsig.wow_pct_points
            window = "day-over-day" if fsig.primary_signal == "dod" else "week-over-week"
            points_str = f" ({points:+.1f}pp {window})" if points is not None else ""
            word = "worsened" if fsig.direction == "spike" else "improved"
            f_headline = f"{f_emoji} *Failure rate {word}*: {rate_str}{points_str}"
        blocks.append(section_block(f_headline))
        blocks.append(
            section_block(
                f"_{current.failed_query_count:,} of {current.query_count:,} queries failed "
                f"yesterday._"
            )
        )

    if (
        signal.unknown_client_share_pct is not None
        and signal.unknown_client_share_pct >= UNKNOWN_CLIENT_FLAG_SHARE_PCT
    ):
        blocks.append(divider_block())
        blocks.append(
            section_block(
                f"⚠️ *{signal.unknown_client_share_pct:.0f}% of yesterday's cost came from an "
                f"unidentified client* (`source` field empty/unset) — worth tracing to a real "
                f"client label."
            )
        )

    if signal.top_clients_current:
        blocks.append(divider_block())
        blocks.append(section_block("*Top clients by scan cost (yesterday)*"))
        blocks.append(
            table_block(
                ["Client", "Cost", "Scanned", "Queries"],
                [_client_row(c) for c in signal.top_clients_current[:MAX_SLACK_CLIENTS]],
            )
        )

    if signal.top_users_current:
        blocks.append(divider_block())
        blocks.append(section_block("*Top users by scan cost (yesterday)*"))
        blocks.append(
            table_block(
                ["User", "Cost", "Scanned", "Queries"],
                [_user_row(u) for u in signal.top_users_current[:MAX_SLACK_USERS]],
            )
        )

    blocks.append(divider_block())
    if action_items:
        blocks.append(section_block("*Action Items*"))
        blocks.append(
            table_block(
                ["Severity", "Issue", "Owner"],
                [
                    [
                        _SEVERITY_EMOJI.get(item["severity"], "🟡"),
                        item["text"],
                        item.get("owner", "no owner assigned"),
                    ]
                    for item in action_items
                ],
            )
        )
        blocks.append(divider_block())

    blocks.append(context_block([f"Generated by Cryo at {generated_at.strftime('%H:%M UTC')}"]))
    return blocks


def _client_row(client: ClientQueryCost) -> list[str]:
    return [
        client.client,
        _fmt_usd(client.estimated_scan_cost_usd),
        _fmt_gb(client.physical_bytes_scanned),
        f"{client.query_count:,}",
    ]


def _user_row(user: UserQueryCost) -> list[str]:
    return [
        user.user_name,
        _fmt_usd(user.estimated_scan_cost_usd),
        _fmt_gb(user.physical_bytes_scanned),
        f"{user.query_count:,}",
    ]


def query_cost_fallback_text(signal: QueryCostSignal, generated_at: datetime) -> str:
    date_str = generated_at.strftime("%Y-%m-%d")
    if signal.current is None:
        return f"Cryo Trino query cost report {date_str}: no data ingested yet"
    cost_str = _fmt_usd(signal.current.estimated_scan_cost_usd)
    return f"Cryo Trino query cost report {date_str}: {signal.direction} — {cost_str}"
