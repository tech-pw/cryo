"""HTML body for the daily fleet report.

Mirrors the facts already on DailyReportData. It does not estimate a figure the
collector did not record. Bytes-freed percentages are omitted unless today's
measurement is a complete total.
"""

from __future__ import annotations

from html import escape

from cryo.reporting.daily_report import DailyReportData, _maintenance_split


def render_daily_report_html(data: DailyReportData, bottom_line: str) -> str:
    date_str = escape(data.report_date.strftime("%B %d, %Y"))
    parts = [
        "<!DOCTYPE html><html><body>",
        f"<h1>Cryo daily report — {date_str}</h1>",
        f"<p>Status: {escape(data.status)}</p>",
        f"<p>{escape(bottom_line)}</p>",
        _table(
            "Fleet",
            ["Metric", "Value"],
            [
                ["Active tables", f"{data.total_tables:,}"],
                ["Healthy", f"{data.healthy_tables:,}"],
                ["Unhealthy", f"{data.unhealthy_tables:,}"],
                ["Scanned yesterday", f"{data.tables_scanned_yesterday:,}"],
                ["Needing compaction", f"{data.tables_needing_compaction:,}"],
                ["Total size", _size_label(data)],
            ],
        ),
        _scan_health(data),
        _maintenance(data),
        _impact(data),
        _grades(data),
        _files(data),
        _cost(data),
        _issues(data),
        (
            "<p>Generated by Cryo. Estimates are labeled; "
            "missing measurements are not shown as zero.</p>"
        ),
        "</body></html>",
    ]
    return "".join(part for part in parts if part)


def _size_label(data: DailyReportData) -> str:
    label = f"{data.total_size_tb:.2f} TB"
    if data.total_size_tb_delta is None:
        return label
    arrow = "up" if data.total_size_tb_delta >= 0 else "down"
    return f"{label} ({arrow} {abs(data.total_size_tb_delta):.2f} TB)"


def _scan_health(data: DailyReportData) -> str:
    health = data.scan_health
    if health is None:
        return ""
    rows = [
        ["Tables in catalog", f"{health.total:,}"],
        ["Passed", f"{health.passed:,}"],
        ["Corrupt (metadata missing in S3)", f"{health.corrupt:,}"],
        ["Failed (permissions / other)", f"{health.failed:,}"],
    ]
    if health.never_scanned:
        rows.append(["Not scanned yet", f"{health.never_scanned:,}"])
    return _table("Scan health", ["Metric", "Tables"], rows)


def _maintenance(data: DailyReportData) -> str:
    rows = _maintenance_split(data.maintenance_stats)
    if not rows:
        return "<h2>Maintenance yesterday</h2><p>No maintenance operations ran.</p>"
    return _table("Maintenance yesterday", ["Operation", "Succeeded", "Failed"], rows)


def _impact(data: DailyReportData) -> str:
    signal = data.impact_signal
    if signal is None:
        return ""
    state = signal.measurement_state
    if state == "unmeasured":
        reclaimed = "unmeasured"
    elif state == "partial":
        reclaimed = f"{signal.today.gb_freed:.1f} GB measured (partial, not a complete total)"
    elif state == "no_actions":
        reclaimed = "no reclaim actions"
    else:
        reclaimed = f"{signal.today.gb_freed:.1f} GB"
    rows = [
        ["Measurement", state],
        ["GB reclaimed", reclaimed],
        ["Successful actions", f"{signal.today.actions_succeeded:,}"],
        ["Tables touched", f"{signal.today.tables_touched:,}"],
    ]
    if signal.today.is_comparable_total:
        if signal.dod_pct is not None:
            rows.append(["Day-over-day", f"{signal.dod_pct:+.1f}%"])
        if signal.wow_pct is not None:
            rows.append(["Week-over-week", f"{signal.wow_pct:+.1f}%"])
    else:
        rows.append(["Trend comparison", "omitted; measurement is not a complete total"])
    return _table("Impact yesterday", ["Metric", "Value"], rows)


def _grades(data: DailyReportData) -> str:
    if not data.grade_distribution:
        return ""
    return _table(
        "Grade distribution",
        ["Grade", "Tables"],
        [[grade, f"{count:,}"] for grade, count in sorted(data.grade_distribution.items())],
    )


def _files(data: DailyReportData) -> str:
    ratio = f"{100 * data.small_files / data.total_files:.1f}%" if data.total_files else "n/a"
    return _table(
        "Files",
        ["Metric", "Value"],
        [
            ["Total files", f"{data.total_files:,}"],
            ["Small files", f"{data.small_files:,}"],
            ["Small-file ratio", ratio],
        ],
    )


def _cost(data: DailyReportData) -> str:
    return _table(
        "Storage cost estimate",
        ["Metric", "Value"],
        [
            ["Estimated monthly cost", f"${data.total_cost_usd:,.0f}"],
            ["Projected monthly savings", f"${data.projected_savings_usd:,.0f}"],
        ],
    )


def _issues(data: DailyReportData) -> str:
    parts: list[str] = []
    if data.action_items:
        items = "".join(
            f"<li>{escape(str(item.get('severity', '')))}: {escape(str(item.get('text', '')))} "
            f"({escape(str(item.get('owner', 'no owner assigned')))})</li>"
            for item in data.action_items
        )
        parts.append(f"<h2>Action items</h2><ul>{items}</ul>")
    if data.top_issues:
        rows = [
            [
                str(issue.get("table", "")),
                str(issue.get("grade", "")),
                str(issue.get("score", "")),
                f"{int(issue.get('small_files') or 0):,}",
            ]
            for issue in data.top_issues[:10]
        ]
        parts.append(_table("Lowest scores", ["Table", "Grade", "Score", "Small files"], rows))
    return "".join(parts)


def _table(title: str, headers: list[str], rows: list[list[str]]) -> str:
    head = "".join(f"<th>{escape(header)}</th>" for header in headers)
    body = "".join(
        "<tr>" + "".join(f"<td>{escape(cell)}</td>" for cell in row) + "</tr>" for row in rows
    )
    return (
        f"<h2>{escape(title)}</h2>"
        f"<table><thead><tr>{head}</tr></thead><tbody>{body}</tbody></table>"
    )
