# ruff: noqa: E501
"""Flink TableMaintenance configuration builder.

Generates Java/YAML configurations for Flink's native Iceberg
TableMaintenance API. Cryo acts as the policy engine; Flink executes.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Any


@dataclass
class FlinkMaintenanceConfig:
    """Configuration for a Flink TableMaintenance job."""

    # Iceberg table location
    catalog_name: str
    catalog_type: str  # rest, glue, hive, hadoop
    catalog_uri: str | None
    table_ref: str  # schema.table

    # Catalog config (passed to CatalogLoader)
    catalog_config: dict[str, str] = field(default_factory=dict)

    # RewriteDataFiles settings
    rewrite_enabled: bool = True
    rewrite_target_file_size_bytes: int = 536870912  # 512 MB
    rewrite_min_file_size_bytes: int = 402653184  # 75% of target
    rewrite_max_file_size_bytes: int = 966367641  # 180% of target
    rewrite_min_input_files: int = 5
    rewrite_partial_progress_enabled: bool = True
    rewrite_max_rewrites_per_commit: int = 100
    rewrite_max_bytes: int | None = None  # None = unlimited
    rewrite_schedule_data_file_count: int | None = 100  # Trigger on file count
    rewrite_schedule_data_file_size_bytes: int | None = None

    # ExpireSnapshots settings
    expire_enabled: bool = True
    expire_max_snapshot_age_ms: int = 7 * 24 * 3600 * 1000  # 7 days
    expire_retain_last: int | None = None
    expire_schedule_interval_ms: int = 3600_000  # Every hour

    # DeleteOrphanFiles settings
    orphan_enabled: bool = False  # Off by default (high I/O)
    orphan_min_file_age_ms: int = 7 * 24 * 3600 * 1000
    orphan_schedule_interval_ms: int = 24 * 3600_000  # Once daily

    # Concurrency lock (required for production)
    lock_type: str = "jdbc"  # jdbc, zookeeper (jdbc is the most common)
    jdbc_url: str | None = None  # Postgres URL for JdbcLockFactory
    jdbc_lock_table: str = "flink_maintenance_locks"

    # Flink job settings
    job_name: str | None = None
    parallelism: int = 1
    checkpoint_interval_ms: int = 60_000

    def to_java_api(self) -> str:
        """Generate Java API code for TableMaintenance."""
        job_name = self.job_name or f"cryo-maintenance-{self.table_ref.replace('.', '-')}"

        lines = [
            "// Generated by Cryo — Flink TableMaintenance configuration",
            "// Iceberg docs: https://iceberg.apache.org/docs/latest/flink-maintenance/",
            "",
            "import org.apache.iceberg.flink.maintenance.api.*;",
            "import org.apache.iceberg.flink.CatalogLoader;",
            "import org.apache.iceberg.flink.TableLoader;",
            "import org.apache.flink.api.common.restartstrategy.RestartStrategies;",
            "import java.time.Duration;",
            "",
            "// Setup execution environment",
            "StreamExecutionEnvironment env = StreamExecutionEnvironment.getExecutionEnvironment();",
            f"env.setParallelism({self.parallelism});",
            f"env.enableCheckpointing({self.checkpoint_interval_ms});",
            "env.setRestartStrategy(RestartStrategies.fixedDelayRestart(3, 10_000));",
            "",
            "// Catalog and table loader",
        ]

        # Catalog loader based on type
        if self.catalog_type == "rest":
            lines += [
                "CatalogLoader catalogLoader = CatalogLoader.rest(",
                f'    "{self.catalog_name}",',
                "    new Configuration(),",
                f'    "{self.catalog_uri}",',
                f"    Map.of({self._catalog_config_java()})",
                ");",
            ]
        elif self.catalog_type == "glue":
            lines += [
                "CatalogLoader catalogLoader = CatalogLoader.custom(",
                f'    "{self.catalog_name}",',
                "    new Configuration(),",
                '    new Path("s3://"),',
                '    "org.apache.iceberg.aws.glue.GlueCatalog"',
                ");",
            ]
        else:
            lines += [
                f"// TODO: Configure {self.catalog_type} catalog loader",
                f'CatalogLoader catalogLoader = CatalogLoader.hive("{self.catalog_name}", new Configuration(), new Path("/"));',
            ]

        schema, table = (
            self.table_ref.split(".", 1) if "." in self.table_ref else ("default", self.table_ref)
        )
        lines += [
            "",
            f'TableIdentifier tableId = TableIdentifier.of("{schema}", "{table}");',
            "TableLoader tableLoader = TableLoader.fromCatalog(catalogLoader, tableId);",
            "",
        ]

        # Lock factory
        if self.lock_type == "jdbc" and self.jdbc_url:
            lines += [
                "// Concurrency lock (prevents concurrent maintenance)",
                "TriggerLockFactory lockFactory = JdbcLockFactory.of(",
                f'    "{self.jdbc_url}",',
                '    "cryo_flink_maintenance",',
                f'    "{self.jdbc_lock_table}"',
                ");",
                "",
            ]
        else:
            lines += [
                "// WARNING: No lock factory configured — use JdbcLockFactory in production",
                "TriggerLockFactory lockFactory = null;",
                "",
            ]

        # TableMaintenance builder
        lines += [
            "// Build maintenance pipeline",
            "TableMaintenance.forTable(env, tableLoader, lockFactory)",
        ]

        if self.rewrite_enabled:
            rewrite_trigger = (
                f".scheduleOnDataFileCount({self.rewrite_schedule_data_file_count})"
                if self.rewrite_schedule_data_file_count
                else f".scheduleOnDataFileSize({self.rewrite_schedule_data_file_size_bytes or 1_073_741_824})"
            )
            rewrite_lines = [
                "    .add(RewriteDataFiles.builder()",
                f"        .targetFileSizeBytes({self.rewrite_target_file_size_bytes})",
                f"        .minFileSizeBytes({self.rewrite_min_file_size_bytes})",
                f"        .maxFileSizeBytes({self.rewrite_max_file_size_bytes})",
                f"        .minInputFiles({self.rewrite_min_input_files})",
                f"        .partialProgressEnabled({str(self.rewrite_partial_progress_enabled).lower()})",
                f"        {rewrite_trigger}",
                "        .build())",
            ]
            lines.extend(rewrite_lines)

        if self.expire_enabled:
            expire_lines = [
                "    .add(ExpireSnapshots.builder()",
                f"        .maxSnapshotAge(Duration.ofMillis({self.expire_max_snapshot_age_ms}))",
                f"        .scheduleWithFixedDelay(Duration.ofMillis({self.expire_schedule_interval_ms}))",
                "        .build())",
            ]
            lines.extend(expire_lines)

        if self.orphan_enabled:
            orphan_lines = [
                "    .add(DeleteOrphanFiles.builder()",
                f"        .olderThan(Duration.ofMillis({self.orphan_min_file_age_ms}))",
                f"        .scheduleWithFixedDelay(Duration.ofMillis({self.orphan_schedule_interval_ms}))",
                "        .build())",
            ]
            lines.extend(orphan_lines)

        lines += [
            "    .append();",
            "",
            f'env.execute("{job_name}");',
        ]

        return "\n".join(lines)

    def to_flink_sql(self) -> str:
        """Generate Flink SQL configuration for maintenance (Flink SQL dialect)."""
        schema, table = (
            self.table_ref.split(".", 1) if "." in self.table_ref else ("default", self.table_ref)
        )

        sql_lines = [
            "-- Generated by Cryo — Flink SQL TableMaintenance configuration",
            "-- Requires: Flink 1.20+ with Iceberg connector and V2 sink enabled",
            "",
            "-- Enable Iceberg V2 sink with maintenance",
            "SET 'table.exec.iceberg.use.v2.sink' = 'true';",
        ]

        if self.rewrite_enabled:
            sql_lines += [
                "",
                "-- Compaction settings",
                "SET 'compaction-enabled' = 'true';",
                f"SET 'flink-maintenance.rewrite.target-file-size-bytes' = '{self.rewrite_target_file_size_bytes}';",
                f"SET 'flink-maintenance.rewrite.min-file-size-bytes' = '{self.rewrite_min_file_size_bytes}';",
                f"SET 'flink-maintenance.rewrite.partial-progress.enabled' = '{str(self.rewrite_partial_progress_enabled).lower()}';",
            ]

        if self.expire_enabled:
            sql_lines += [
                "",
                "-- Snapshot expiration",
                "SET 'flink-maintenance.expire-snapshots.enabled' = 'true';",
                f"SET 'flink-maintenance.expire-snapshots.max-snapshot-age-seconds' = '{self.expire_max_snapshot_age_ms // 1000}';",
            ]

        if self.orphan_enabled:
            sql_lines += [
                "",
                "-- Orphan file cleanup",
                "SET 'flink-maintenance.delete-orphan-files.enabled' = 'true';",
            ]

        sql_lines += [
            "",
            "-- Insert into your streaming table to activate post-commit maintenance",
            f"INSERT INTO {self.catalog_name}.{self.table_ref} ...",
        ]

        return "\n".join(sql_lines)

    def _catalog_config_java(self) -> str:
        """Generate Java Map.of() entries for catalog config."""
        if not self.catalog_config:
            return ""
        pairs = [f'"{k}", "{v}"' for k, v in list(self.catalog_config.items())[:5]]
        return ", ".join(pairs)

    @classmethod
    def from_cryo_params(
        cls,
        table_ref: str,
        catalog_name: str,
        catalog_type: str,
        catalog_uri: str | None,
        params: dict[str, Any],
    ) -> FlinkMaintenanceConfig:
        """Create config from Cryo maintenance parameters."""
        return cls(
            catalog_name=catalog_name,
            catalog_type=catalog_type,
            catalog_uri=catalog_uri,
            table_ref=table_ref,
            rewrite_target_file_size_bytes=int(params.get("target_file_size_bytes", 536870912)),
            rewrite_min_input_files=int(
                params.get("min_input_files", params.get("min_small_files", 5))
            ),
            rewrite_partial_progress_enabled=True,
            expire_max_snapshot_age_ms=(
                int(params["retention_hours"]) * 3600 * 1000
                if params.get("retention_hours")
                else int(params.get("retention_days", 7)) * 24 * 3600 * 1000
            ),
        )
