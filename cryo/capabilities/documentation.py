from __future__ import annotations

from collections.abc import Iterable

from cryo.capabilities.manifest import CAPABILITY_MANIFEST
from cryo.capabilities.models import CapabilityEvidence, CapabilityManifest


def _escape(value: str) -> str:
    return value.replace("|", "\\|").replace("\n", " ")


def _join(values: Iterable[str]) -> str:
    rendered = tuple(values)
    return "<br>".join(_escape(value) for value in rendered) if rendered else "-"


def _evidence_links(evidence: tuple[CapabilityEvidence, ...]) -> str:
    return "<br>".join(
        f"[{item.kind}: `{_escape(item.symbol)}`](../{_escape(item.path)})" for item in evidence
    )


def render_capabilities_markdown(
    manifest: CapabilityManifest = CAPABILITY_MANIFEST,
) -> str:
    lines = [
        "# Cryo capability contract",
        "",
        "<!-- Generated by `python -m cryo.capabilities.generate_docs`; do not edit. -->",
        "",
        f"Manifest schema: `{manifest.schema_version}`  ",
        f"Canonical source: `{manifest.source}`",
        "",
        "This document states what Cryo can execute today. A configured connection does not imply",
        "operation support: conditional, fallback-only, experimental, and blocked paths are "
        "explicit.",
        "",
        "## Maturity",
        "",
        "| Tier | Meaning |",
        "|---|---|",
    ]
    lines.extend(
        f"| **{item.tier.value.upper()}** | {_escape(item.meaning)} |"
        for item in manifest.maturity_definitions
    )

    lines.extend(
        [
            "",
            "## Catalog read support",
            "",
            "| Catalog | Protocol | Maturity | Aliases | Capabilities | Limitations | Evidence |",
            "|---|---|---|---|---|---|---|",
        ]
    )
    lines.extend(
        "| {label} (`{catalog_type}`) | {protocol} | **{maturity}** | {aliases} | "
        "{capabilities} | {limitations} | {evidence} |".format(
            label=_escape(catalog.label),
            catalog_type=_escape(catalog.catalog_type),
            protocol=_escape(catalog.protocol),
            maturity=catalog.maturity.value.upper(),
            aliases=_join(f"`{alias}`" for alias in catalog.aliases),
            capabilities=_join(catalog.capabilities),
            limitations=_join(catalog.limitations),
            evidence=_evidence_links(catalog.evidence),
        )
        for catalog in manifest.catalogs
    )

    lines.extend(
        [
            "",
            "## Engine status",
            "",
            "| Engine | Maturity | Executes work | Contract | Limitations | Owner | Evidence |",
            "|---|---|---:|---|---|---|---|",
        ]
    )
    lines.extend(
        "| {label} (`{engine}`) | **{maturity}** | {executes} | {summary} | "
        "{limitations} | `{owner}` | {evidence} |".format(
            label=_escape(engine.label),
            engine=engine.engine.value,
            maturity=engine.maturity.value.upper(),
            executes="Yes" if engine.execution_available else "No",
            summary=_escape(engine.summary),
            limitations=_join(engine.limitations),
            owner=_escape(engine.owner),
            evidence=_evidence_links(engine.evidence),
        )
        for engine in manifest.engines
    )

    operation_labels = {item.operation: item.label for item in manifest.operations}
    lines.extend(
        [
            "",
            "## Engine x operation matrix",
            "",
            "| Engine | Operation | Support | Maturity | Execution | Effect strategy | "
            "Runtime conditions | Fallbacks | Limitations | Evidence |",
            "|---|---|---|---|---|---|---|---|---|---|",
        ]
    )
    lines.extend(
        "| `{engine}` | {operation} (`{operation_key}`) | **{support}** | {maturity} | "
        "`{execution}` | `{effect_strategy}` | {conditions} | {fallbacks} | {limitations} | "
        "{evidence} |".format(
            engine=cell.engine.value,
            operation=_escape(operation_labels[cell.operation]),
            operation_key=cell.operation.value,
            support=cell.support.value.replace("_", " ").upper(),
            maturity=cell.maturity.value.upper(),
            execution=cell.execution_mode.value,
            effect_strategy=cell.effect_strategy.value,
            conditions=_join(cell.runtime_conditions),
            fallbacks=_join(f"`{item.value}`" for item in cell.fallback_engines),
            limitations=_join(cell.limitations),
            evidence=_evidence_links(cell.evidence),
        )
        for cell in manifest.matrix
    )

    lines.extend(
        [
            "",
            "## Drift policy",
            "",
            "- Every `EngineType x OperationType` pair must have exactly one matrix cell.",
            "- Runtime routing, the API, the Connections UI, and this document consume the same "
            "manifest.",
            "- Evidence paths and symbols are executable contracts, not readiness claims by "
            "themselves.",
            "- CI fails when this generated document differs from the canonical manifest.",
            "",
        ]
    )
    return "\n".join(lines)
